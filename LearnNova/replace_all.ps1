function Replace-InFile ($Path, $Old, $New) {
    if (Test-Path $Path) {
        $Content = [IO.File]::ReadAllText($Path, [System.Text.Encoding]::UTF8)
        $Content = $Content.Replace($Old, $New)
        [IO.File]::WriteAllText($Path, $Content, [System.Text.Encoding]::UTF8)
    }
}

